const gasNumbers = new Set([1, 2, 7, 8, 9, 10, 17, 18, 36, 54, 86]);
const liquidNumbers = new Set([35, 80]);

export const elements: ElementData[] = rows.map(
  ([
    number,
    symbol,
    name,
    englishName,
    atomicMass,
    categoryId,
    period,
    group,
    summary,
    discovery,
    uses,
  ]) => ({
    number,
    symbol,
    name,
    englishName,
    atomicMass,
    categoryId,
    period,
    group,
    phase:
      number >= 100 || number === 85 || number === 87
        ? "unknown"
        : gasNumbers.has(number)
          ? "gas"
          : liquidNumbers.has(number)
            ? "liquid"
            : "solid",
    summary,
    discovery,
    uses,
    sourceUrl: `https://periodic-table.rsc.org/element/${number}/${englishName.toLowerCase()}`,
    ...(number === 11 ? { shells: [2, 8, 1] } : {}),
  }),
);

export function getElement(value: number | string): ElementData | undefined {
  return elements.find((element) =>
    typeof value === "number"
      ? element.number === value
      : element.symbol.toLowerCase() === value.toLowerCase() ||
        element.englishName.toLowerCase() === value.toLowerCase() ||
        element.name === value ||
        String(element.number) === value,
  );
}
